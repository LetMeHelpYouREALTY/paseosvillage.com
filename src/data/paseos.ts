const byId = new Map(facts.map((fact) => [fact.id, fact]));

export function factById(id: string): Fact | undefined {
  return byId.get(id);
}

export function publishedFacts(ids: string[]): Fact[] {
  return ids
    .map((id) => byId.get(id))
    .filter((fact): fact is Fact => Boolean(fact && fact.publish && fact.value));
}

export function unpublishedFacts(): Fact[] {
  return facts.filter((fact) => !fact.publish || fact.value === null || !fact.verified);
}

